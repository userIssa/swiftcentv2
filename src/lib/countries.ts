export function findCountryOption(input?: string | null): CountryOption | null {
  if (!input || !input.trim()) return null;
  const q = input.trim().toLowerCase();
  return (
    SUPPORTED_COUNTRIES.find(
      (c) =>
        c.name.toLowerCase() === q ||
        c.code.toLowerCase() === q ||
        (q === 'usa' && c.code === 'US') ||
        (q === 'uk' && c.code === 'GB') ||
        (q === 'uae' && c.code === 'AE')
    ) || null
  );
}

